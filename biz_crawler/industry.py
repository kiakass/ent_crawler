@lru_cache(maxsize=1)
def taxonomy() -> dict[str, tuple[str, str, str]]:
    """소 → (대, 중, 소). 자리표시 행은 뺀다."""
    out: dict[str, tuple[str, str, str]] = {}
    with TAXONOMY.open(encoding="utf-8", newline="") as f:
        for i, row in enumerate(csv.reader(f)):
            if i == 0 or len(row) < 3:
                continue
            large, mid, small = (c.strip() for c in row[:3])
            if not small or _PLACEHOLDER.search(large):
                continue
            if small in out:
                raise ValueError(f"업종분류.md 에 소 '{small}' 가 중복됩니다")
            out[small] = (large, mid, small)
    return out


@lru_cache(maxsize=1)
def _compiled() -> tuple[list, list, list]:
    tax = taxonomy()
    cat = [(re.compile(p), s) for p, s in _CATEGORY_RULES]
    name = [(re.compile(p), s) for p, s in _NAME_RULES]
    nps = [(re.compile(p), s) for p, s in _NPS_RULES]
    used = {s for _, s in cat + name + nps if s} | set(_NPS_PREFIX.values()) | {DEFAULT_SMALL}
    missing = sorted(used - tax.keys())
    if missing:
        raise ValueError(f"업종분류.md 에 없는 소: {', '.join(missing)}")
    return cat, name, nps


def split_category(category: str | None) -> tuple[str, str, str]:
    """'음식점>일식>돈가스' → ('음식점', '일식', '돈가스'). 4단계 이상은 소에 '>' 로 붙인다."""
    parts = [p.strip() for p in (category or "").split(">") if p.strip()]
    return (parts[0] if parts else "",
            parts[1] if len(parts) > 1 else "",
            ">".join(parts[2:]))


def _by_category(category: str) -> str | None:
    cat_rules, _, _ = _compiled()
    for pat, small in cat_rules:
        if pat.search(category):
            return small
    return None


def _by_nps(row: dict) -> str | None:
    """국민연금 업종명 키워드 → 코드 앞 2자리 기본값 순."""
    from .nps_bplc import NO_INDUSTRY_PREFIX

    if row.get("nps_status") != "matched":
        return None
    code = (row.get("nps_code") or "").strip()
    if not code or code.startswith(NO_INDUSTRY_PREFIX):
        return None
    _, _, nps_rules = _compiled()
    industry = (row.get("nps_industry") or "").strip()
    for pat, small in nps_rules:
        if pat.search(industry):
            return small
    return _NPS_PREFIX.get(code[:2])


def _by_name(name: str) -> str | None:
    _, name_rules, _ = _compiled()
    for pat, small in name_rules:
        if pat.search(name):
            return small
    return None


def classify(row: dict) -> dict[str, str]:
    """마스터 행 1건의 업종 컬럼(RESULT_FIELDS)을 돌려준다."""
    # low_score 업소는 다른 업소일 수 있어 카테고리를 내보내지도, 쓰지도 않는다.
    from .merge import naver_trusted   # 순환 import 회피
    matched = naver_trusted(row)
    category = (row.get("naver_category") or "").strip() if matched else ""
    l1, l2, l3 = split_category(category)
    out = {"ind_naver_l1": l1, "ind_naver_l2": l2, "ind_naver_l3": l3}

    small, basis = _by_nps(row), "국민연금업종"
    if small is None and category:
        small, basis = _by_category(category), "NAVER카테고리"
    if small is None:
        name = (row.get("final_company_name") or row.get("input_name") or "").strip()
        small, basis = _by_name(name), "상호명키워드"
    if small is None:
        small, basis = DEFAULT_SMALL, "기본값"

    large, mid, small = taxonomy().get(small or "", ("", "", ""))
    out.update(ind_large=large, ind_mid=mid, ind_small=small, ind_basis=basis)
    return out
